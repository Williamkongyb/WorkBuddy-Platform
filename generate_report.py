def set_cell_text(cell, text, bold=False, font_name='微软雅黑', font_size=Pt(10), alignment=WD_ALIGN_PARAGRAPH.CENTER, color=None):
    """设置单元格文本"""
    # 清除默认段落
    for p in cell.paragraphs:
        p.clear()
    p = cell.paragraphs[0]
    p.alignment = alignment
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run(str(text))
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = font_size
    run.bold = bold
    if color:
        run.font.color.rgb = color
    return p

def set_cell_shading(cell, color):
    """设置单元格底色"""
    shading_elm = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color}"/>')
    cell._element.get_or_add_tcPr().append(shading_elm)

def create_table(headers, rows, col_widths=None):
    """创建格式化表格"""
    num_cols = len(headers)
    table = doc.add_table(rows=1 + len(rows), cols=num_cols)
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True

    # 设置表头
    for i, header in enumerate(headers):
        cell = table.rows[0].cells[i]
        set_cell_text(cell, header, bold=True, font_size=Pt(10), color=RGBColor(255, 255, 255))
        set_cell_shading(cell, '2F5496')

    # 设置数据行
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = table.rows[r + 1].cells[c]
            set_cell_text(cell, val, bold=False, font_size=Pt(10))
            if r % 2 == 0:
                set_cell_shading(cell, 'F2F7FB')

    return table

